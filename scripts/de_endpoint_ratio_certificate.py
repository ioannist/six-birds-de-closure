#!/usr/bin/env python3
"""Exact unimodal-cell certificates for the actual positive endpoint ratio.

Fraction and integer isqrt only. Default mode replays generated bytes.
--write generates a new certificate packet without changing previous receipts.
"""
from __future__ import annotations
import argparse
from fractions import Fraction
import json
from math import isqrt
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LEAN = ROOT / 'lean/SbtCosmo/Derivation/WindowEndpointRatioData.lean'
RECEIPT = ROOT / 'results/endpoint_ratio_2026-10-03/cells.json'
PRECISION = 1_000_000
LAMBDA = Fraction(17, 5)


def generate() -> tuple[str, str]:
    f = Fraction
    grid = ([f(1, 1000)] + [f(j, 320) for j in range(1, 321)]
            + [f(j, 160) for j in range(161, 321)]
            + [f(j, 64) for j in range(129, 257)]
            + [f(j, 12) for j in range(49, 97)]
            + [f(j, 4) for j in range(33, 81)])
    assert len(grid) == 705 and grid[512] == f(5, 2) and grid[-1] == 20
    def q(a: Fraction) -> Fraction:
        return a**3 / (1 + LAMBDA * a**3)**3
    def floor_sqrt(v: Fraction) -> Fraction:
        return f(isqrt(v.numerator * PRECISION**2 // v.denominator), PRECISION)
    def ceil_sqrt(v: Fraction) -> Fraction:
        return floor_sqrt(v) + f(1, PRECISION)
    lower, upper, branches = [], [], []
    for a, b in zip(grid, grid[1:]):
        lower.append(floor_sqrt(min(q(a), q(b))))
        if 2 * LAMBDA * b**3 <= 1:
            u, branch = q(b), 'increasing'
        elif 1 <= 2 * LAMBDA * a**3:
            u, branch = q(a), 'decreasing'
        else:
            u, branch = f(4)/(27*LAMBDA), 'peak'
        upper.append(ceil_sqrt(u))
        branches.append(branch)
    def validate(lows: list[Fraction], highs: list[Fraction]) -> None:
        for a, b, lo, hi in zip(grid, grid[1:], lows, highs):
            assert 0 < a <= b and 0 <= lo and 0 <= hi
            assert lo**2 * (1+LAMBDA*a**3)**3 <= a**3
            assert lo**2 * (1+LAMBDA*b**3)**3 <= b**3
            assert ((2*LAMBDA*b**3 <= 1 and b**3 <= hi**2*(1+LAMBDA*b**3)**3)
                    or (1 <= 2*LAMBDA*a**3 and a**3 <= hi**2*(1+LAMBDA*a**3)**3)
                    or 4 <= 27*LAMBDA*hi**2)
    validate(lower, upper)
    controls = {}
    for kind in ('lower', 'upper'):
        bad_lo, bad_hi = lower.copy(), upper.copy()
        if kind == 'lower':
            bad_lo[0] = f(1)
        else:
            bad_hi[0] = f(0)
        try:
            validate(bad_lo, bad_hi)
        except AssertionError:
            controls[kind] = True
        else:
            raise AssertionError(f'False {kind} certificate escaped validation')
    lower_sum = sum(((grid[i+1]-grid[i])*lower[i] for i in range(512)), f(0))
    upper_sum = sum(((grid[i+1]-grid[i])*upper[i] for i in range(704)), f(0))
    assert f(1938, 10000) <= lower_sum and upper_sum <= f(2082, 10000)
    def vector(vs: list[Fraction]) -> str:
        return '![' + ', '.join(f'({v.numerator} / {v.denominator})' for v in vs) + ']'
    def chunked(name: str, values: list[Fraction], default: int) -> str:
        chunks = [values[i:i+128] for i in range(0, len(values), 128)]
        out = ''.join(f'def {name}Block{k} : Fin {len(vs)} → ℚ :=\n  {vector(vs)}\n'
                      for k, vs in enumerate(chunks))
        out += f'def {name} (i : ℕ) : ℚ :=\n  '
        for k, vs in enumerate(chunks):
            end = k*128 + len(vs)
            index = 'i' if k == 0 else f'i - {k*128}'
            out += f'if h : i < {end} then {name}Block{k} ⟨{index}, by omega⟩ else\n  '
        out += str(default) + '\n'
        return out
    declarations = chunked('grid', grid, 20) + chunked('lower', lower[:512], 0) + chunked('upper', upper, 1)
    lean = f'''import Mathlib.Tactic

/-! Exact endpoint/prefix certificates for the sharp native integrand enclosure.
Generated by scripts/de_endpoint_ratio_certificate.py; checked in Lean's kernel. -/
namespace SbtCosmo.Derivation.WindowEndpointRatioData
set_option maxRecDepth 100000
set_option maxHeartbeats 50000000

{declarations}

theorem grid_endpoints : grid 0 = (1 : ℚ) / 1000 ∧ grid 512 = 5 / 2 ∧ grid 704 = 20 := by
  decide +kernel

theorem lower_cells : ∀ i : Fin 512,
    0 < grid i ∧ grid i ≤ grid (i + 1) ∧ 0 ≤ lower i ∧
      (lower i)^2 * (1 + (17/5) * (grid i)^3)^3 ≤ (grid i)^3 ∧
      (lower i)^2 * (1 + (17/5) * (grid (i+1))^3)^3 ≤ (grid (i+1))^3 := by
  decide +kernel

theorem upper_cells : ∀ i : Fin 704,
    0 < grid i ∧ grid i ≤ grid (i + 1) ∧ 0 ≤ upper i ∧
      ((2 * (17/5) * (grid (i+1))^3 ≤ 1 ∧
        (grid (i+1))^3 ≤ (upper i)^2 * (1 + (17/5) * (grid (i+1))^3)^3) ∨
      (1 ≤ 2 * (17/5) * (grid i)^3 ∧
        (grid i)^3 ≤ (upper i)^2 * (1 + (17/5) * (grid i)^3)^3) ∨
      4 ≤ 27 * (17/5) * (upper i)^2) := by
  decide +kernel

theorem lower_sum : (1938 : ℚ) / 10000 ≤
    ∑ i ∈ Finset.range 512, (grid (i + 1) - grid i) * lower i := by
  decide +kernel

theorem upper_sum : (∑ i ∈ Finset.range 704, (grid (i+1) - grid i) * upper i) ≤ (2082 : ℚ) / 10000 := by
  decide +kernel

end SbtCosmo.Derivation.WindowEndpointRatioData
'''
    receipt = {'arithmetic':'Python Fraction and integer isqrt; no floating arithmetic',
        'lambda':str(LAMBDA),'domain':['1/1000','20'],'prefix_domain':['1/1000','5/2'],
        'vector_chunk_size':128,'cells':704,'prefix_cells':512,'sqrt_enclosure_denominator':PRECISION,
        'lower_prefix_sum':str(lower_sum),'upper_sum':str(upper_sum),
        'lower_prefix_certificate':'1938/10000','upper_certificate':'2082/10000',
        'false_certificate_controls':controls,
        'grid':list(map(str,grid)), 'prefix_lower':list(map(str,lower[:512])),
        'upper':list(map(str,upper)), 'upper_branch':branches}
    return lean,json.dumps(receipt,indent=2)+'\n'


def main() -> None:
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write',action='store_true')
    args=parser.parse_args()
    lean,receipt=generate()
    for path,content in ((LEAN,lean),(RECEIPT,receipt)):
        if args.write:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_text(content)
        else:
            assert path.read_bytes()==content.encode(),f'Certificate drift: {path}'
    print('Exact 704-cell endpoint / 512-cell prefix certificates and both false-certificate controls passed; '
          + ('artifacts written.' if args.write else 'artifact byte replay matched.'))

if __name__=='__main__':
    main()
