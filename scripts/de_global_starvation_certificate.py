#!/usr/bin/env python3
"""Exact upper-cell certificate for the actual all-time starvation cutoff.

Fraction and integer isqrt only. Default mode replays generated bytes.
--write generates a new certificate packet without changing previous receipts.
"""
from __future__ import annotations
import argparse
from fractions import Fraction
import json
from math import isqrt
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LEAN = ROOT / 'lean/SbtCosmo/Derivation/WindowStarvationData.lean'
RECEIPT = ROOT / 'results/global_starvation_2026-10-03/cells.json'
PRECISION = 1_000_000
LAMBDA = Fraction(32)


def generate() -> tuple[str, str]:
    f = Fraction
    grid = ([f(1, 1000)] + [f(j, 32) for j in range(1, 33)]
            + [f(j, 16) for j in range(17, 33)]
            + [f(j, 8) for j in range(17, 33)])
    assert len(grid)==65 and grid[-1]==4 and f(1,4) in grid
    def q(a: Fraction) -> Fraction:
        return a**3 / (1 + LAMBDA * a**3)**3
    def floor_sqrt(v: Fraction) -> Fraction:
        return f(isqrt(v.numerator * PRECISION**2 // v.denominator), PRECISION)
    def ceil_sqrt(v: Fraction) -> Fraction:
        return floor_sqrt(v) + f(1, PRECISION)
    upper, branches = [], []
    for a, b in zip(grid, grid[1:]):
        if 2 * LAMBDA * b**3 <= 1:
            u, branch = q(b), 'increasing'
        elif 1 <= 2 * LAMBDA * a**3:
            u, branch = q(a), 'decreasing'
        else:
            u, branch = f(4)/(27*LAMBDA), 'peak'
        upper.append(ceil_sqrt(u))
        branches.append(branch)
    def validate(highs: list[Fraction]) -> None:
        for a, b, hi in zip(grid, grid[1:], highs):
            assert 0 < a <= b and 0 <= hi
            assert ((2*LAMBDA*b**3 <= 1 and b**3 <= hi**2*(1+LAMBDA*b**3)**3)
                    or (1 <= 2*LAMBDA*a**3 and a**3 <= hi**2*(1+LAMBDA*a**3)**3)
                    or 4 <= 27*LAMBDA*hi**2)
    validate(upper)
    controls = {}
    bad = upper.copy()
    bad[0] = f(0)
    try:
        validate(bad)
    except AssertionError:
        controls['zero_upper_cell_rejected'] = True
    else:
        raise AssertionError('False upper certificate escaped validation')
    upper_sum = sum(((grid[i+1]-grid[i])*upper[i] for i in range(64)), f(0))
    assert upper_sum <= f(341, 10000)
    try:
        assert upper_sum <= f(34, 1000)
    except AssertionError:
        controls['lowered_sum_target_rejected'] = True
    else:
        raise AssertionError('Lowered sum target escaped validation')
    def vector(vs: list[Fraction]) -> str:
        return '![' + ', '.join(f'({v.numerator} / {v.denominator})' for v in vs) + ']'
    def chunked(name: str, values: list[Fraction], default: int) -> str:
        chunks = [values[i:i+128] for i in range(0, len(values), 128)]
        out = ''.join(f'def {name}Block{k} : Fin {len(vs)} → ℚ :=\n  {vector(vs)}\n'
                      for k, vs in enumerate(chunks))
        out += f'def {name} (i : ℕ) : ℚ :=\n  '
        for k, vs in enumerate(chunks):
            end = k*128 + len(vs)
            index = 'i' if k == 0 else f'i - {k*128}'
            out += f'if h : i < {end} then {name}Block{k} ⟨{index}, by omega⟩ else\n  '
        out += str(default) + '\n'
        return out
    declarations = chunked('grid', grid, 4) + chunked('upper', upper, 1)
    lean = f'''import Mathlib.Tactic

/-! Exact all-time starvation upper certificate for the sharp native integrand enclosure.
Generated by scripts/de_global_starvation_certificate.py; checked in Lean's kernel. -/
namespace SbtCosmo.Derivation.WindowStarvationData
set_option maxRecDepth 100000
set_option maxHeartbeats 50000000

{declarations}

theorem grid_endpoints : grid 0 = (1 : ℚ) / 1000 ∧ grid 64 = 4 := by
  decide +kernel

theorem upper_cells : ∀ i : Fin 64,
    0 < grid i ∧ grid i ≤ grid (i + 1) ∧ 0 ≤ upper i ∧
      ((2 * 32 * (grid (i+1))^3 ≤ 1 ∧
        (grid (i+1))^3 ≤ (upper i)^2 * (1 + 32 * (grid (i+1))^3)^3) ∨
      (1 ≤ 2 * 32 * (grid i)^3 ∧
        (grid i)^3 ≤ (upper i)^2 * (1 + 32 * (grid i)^3)^3) ∨
      4 ≤ 27 * 32 * (upper i)^2) := by
  decide +kernel

theorem upper_sum : (∑ i ∈ Finset.range 64, (grid (i+1) - grid i) * upper i) ≤ (341 : ℚ) / 10000 := by
  decide +kernel

end SbtCosmo.Derivation.WindowStarvationData
'''
    receipt = {'arithmetic':'Python Fraction and integer isqrt; no floating arithmetic',
        'lambda':str(LAMBDA),'domain':['1/1000','4'],
        'vector_chunk_size':128,'cells':64,'sqrt_enclosure_denominator':PRECISION,
        'upper_sum':str(upper_sum),
        'upper_certificate':'341/10000',
        'false_certificate_controls':controls,
        'grid':list(map(str,grid)),
        'upper':list(map(str,upper)), 'upper_branch':branches}
    return lean,json.dumps(receipt,indent=2)+'\n'


def main() -> None:
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write',action='store_true')
    args=parser.parse_args()
    lean,receipt=generate()
    for path,content in ((LEAN,lean),(RECEIPT,receipt)):
        if args.write:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_text(content)
        else:
            assert path.read_bytes()==content.encode(),f'Certificate drift: {path}'
    print('Exact 64-cell all-time starvation upper certificate and both false-certificate controls passed; '
          + ('artifacts written.' if args.write else 'artifact byte replay matched.'))

if __name__=='__main__':
    main()
