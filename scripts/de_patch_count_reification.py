#!/usr/bin/env python3
"""Reify the original N=32/N=128 robustness populations, without solving growth.

NumPy's actual draw order and binary amplitudes are retained. Default: byte
replay; --write: generate the new Lean/JSON inputs. Kernel proofs check all
maxima, rank counts, admissibility bounds and cross-population ordering.
"""
from __future__ import annotations

import argparse
from fractions import Fraction
import hashlib
import json
from pathlib import Path
import platform

import numpy as np

import de_window_carrier as window

ROOT = Path(__file__).resolve().parents[1]
LEAN = ROOT / "lean/SbtCosmo/Derivation/WindowPatchCountData.lean"
DATA = ROOT / "results/patch_count_2026-10-03/populations.json"


def rational(value: Fraction) -> str:
    return f"({value.numerator} / {value.denominator})"


def vector(values: list[str]) -> str:
    return "![" + ", ".join(values) + "]"


def realize(n: int, cfg: window.CarrierConfig) -> list[dict]:
    rows = []
    delta = Fraction(str(cfg.delta_c))
    for seed in window.SEEDS:
        rng = np.random.default_rng(seed)
        samples = cfg.heterogeneity_s * np.abs(rng.normal(size=n))
        amplitudes = [Fraction.from_float(float(x)) for x in samples]
        tags = [bool(x) for x in rng.random(n) < cfg.tag_probability]
        indices = [max((i for i, tag in enumerate(tags) if tag == b),
                       key=amplitudes.__getitem__) for b in [False, True]]
        maxima = [amplitudes[i] for i in indices]
        assert len(amplitudes) == len(tags) == n
        assert all(a >= 0 for a in amplitudes) and all(m > 0 for m in maxima)
        rows.append({
            "seed": seed,
            "amplitudes_exact": [str(a) for a in amplitudes],
            "tags": tags,
            "tag_maximum_indices": indices,
            "tag_maxima_exact": [str(m) for m in maxima],
            "threshold_exact": str(max(delta / m for m in maxima)),
        })
    return rows


def rank_certificate(rows: list[dict], threshold: Fraction) -> bool:
    values = [Fraction(row["threshold_exact"]) for row in rows]
    return sum(t < threshold for t in values) == 9 and sum(t <= threshold for t in values) == 10


def construct() -> tuple[str, str]:
    if np.__version__ != "1.26.4":
        raise RuntimeError("The original realization uses NumPy 1.26.4.")
    cfg = window.CarrierConfig()
    assert cfg.n_patches == 64 and len(window.SEEDS) == 12
    assert (cfg.a_init, cfg.a_max, cfg.delta_c, cfg.seed_pass_fraction) == (.001, 20, 1.686, .8)
    assert (cfg.heterogeneity_s, cfg.tag_probability) == (.001, .5)
    original = json.loads((ROOT / "results/window_population_2026-10-03/population.json").read_text())
    baseline = realize(64, cfg)
    assert baseline == original["populations"]
    groups = [realize(n, cfg) for n in [32, 128]]
    aggregates = [sorted(Fraction(row["threshold_exact"]) for row in rows)[9] for rows in groups]
    original_aggregate = Fraction(original["aggregate_threshold_exact"])
    assert aggregates[1] < original_aggregate < aggregates[0]
    assert all(rank_certificate(rows, agg) for rows, agg in zip(groups, aggregates))
    assert all(not rank_certificate(rows, 2 * agg) for rows, agg in zip(groups, aggregates))
    assert not rank_certificate(groups[0], original_aggregate)
    assert not rank_certificate(groups[1], original_aggregate)
    assert Fraction(1252) < aggregates[0] < 1253 and Fraction(804) < aggregates[1] < 805

    lean = """import SbtCosmo.Derivation.WindowSampleData

/-! Original separately realized patch-count populations. false denotes N=32,
true denotes N=128. No population inclusion or tag coupling is assumed.
Generated by scripts/de_patch_count_reification.py with NumPy 1.26.4;
all certificates use the Lean kernel. The RNG itself is not formalized. -/
namespace SbtCosmo.Derivation.WindowPatchCountData
set_option maxRecDepth 100000
set_option maxHeartbeats 40000000

abbrev patchCount : Bool → ℕ
  | false => 32
  | true => 128

"""
    definitions = [
        ("amplitudeRat : (v : Bool) → Fin 12 → Fin (patchCount v) → ℚ",
         [vector([vector([rational(Fraction(a)) for a in row["amplitudes_exact"]]) for row in rows]) for rows in groups]),
        ("tag : (v : Bool) → Fin 12 → Fin (patchCount v) → Bool",
         [vector([vector([str(b).lower() for b in row["tags"]]) for row in rows]) for rows in groups]),
        ("falseIndex : (v : Bool) → Fin 12 → Fin (patchCount v)",
         [vector([str(row["tag_maximum_indices"][0]) for row in rows]) for rows in groups]),
        ("trueIndex : (v : Bool) → Fin 12 → Fin (patchCount v)",
         [vector([str(row["tag_maximum_indices"][1]) for row in rows]) for rows in groups]),
        ("maximumFalseRat : Bool → Fin 12 → ℚ",
         [vector([rational(Fraction(row["tag_maxima_exact"][0])) for row in rows]) for rows in groups]),
        ("maximumTrueRat : Bool → Fin 12 → ℚ",
         [vector([rational(Fraction(row["tag_maxima_exact"][1])) for row in rows]) for rows in groups]),
        ("thresholdRat : Bool → Fin 12 → ℚ",
         [vector([rational(Fraction(row["threshold_exact"])) for row in rows]) for rows in groups]),
        ("aggregateRat : Bool → ℚ", [rational(t) for t in aggregates]),
    ]
    for name, values in definitions:
        lean += f"def {name}\n  | false => {values[0]}\n  | true => {values[1]}\n\n"
    lean += """theorem rational_maxima_certificate : ∀ (v : Bool) (j : Fin 12),
    0 < maximumFalseRat v j ∧ 0 < maximumTrueRat v j ∧
    tag v j (falseIndex v j) = false ∧ amplitudeRat v j (falseIndex v j) = maximumFalseRat v j ∧
    tag v j (trueIndex v j) = true ∧ amplitudeRat v j (trueIndex v j) = maximumTrueRat v j ∧
    ∀ i : Fin (patchCount v), 0 ≤ amplitudeRat v j i ∧
      (tag v j i = false → amplitudeRat v j i ≤ maximumFalseRat v j) ∧
      (tag v j i = true → amplitudeRat v j i ≤ maximumTrueRat v j) := by
  decide +kernel

theorem rational_threshold_certificate : ∀ (v : Bool) (j : Fin 12),
    thresholdRat v j = max (WindowSampleData.deltaRat / maximumFalseRat v j)
      (WindowSampleData.deltaRat / maximumTrueRat v j) := by
  decide +kernel

theorem rational_rank_certificate : ∀ v : Bool,
    (Finset.univ.filter (fun j : Fin 12 => thresholdRat v j < aggregateRat v)).card = 9 ∧
    (Finset.univ.filter (fun j : Fin 12 => thresholdRat v j ≤ aggregateRat v)).card = 10 := by
  decide +kernel

theorem rational_window_bounds : ∀ v : Bool,
    (3 : ℚ) / 2 < aggregateRat v ∧ aggregateRat v < 20000 := by
  decide +kernel

theorem rational_tight_bounds : (1252 : ℚ) < aggregateRat false ∧ aggregateRat false < 1253 ∧
    804 < aggregateRat true ∧ aggregateRat true < 805 := by
  decide +kernel

theorem rational_threshold_order : aggregateRat true < WindowSampleData.aggregateRat ∧
    WindowSampleData.aggregateRat < aggregateRat false := by
  decide +kernel

end SbtCosmo.Derivation.WindowPatchCountData
"""
    paths = ["scripts/de_patch_count_reification.py", "scripts/de_window_carrier.py",
             "lean/SbtCosmo/Derivation/WindowSampleData.lean",
             "results/window_population_2026-10-03/population.json"]
    data = {
        "scope": "Original separately seeded N=32/N=128 realized amplitudes and tags; exact decimal mathematical model scalars; no solver or RNG proof",
        "software": {"python": platform.python_version(), "numpy": np.__version__},
        "model_scalars_decimal": original["model_scalars_decimal"],
        "required_seeds": 10,
        "original_64_population_replayed_exactly": True,
        "variants": [{"n_patches": n, "lean_variant": v, "populations": rows,
                      "aggregate_threshold_exact": str(agg),
                      "rank_counts": {"strictly_below": 9, "at_or_below": 10}}
                     for n, v, rows, agg in zip([32, 128], [False, True], groups, aggregates)],
        "threshold_order_exact_checked": True,
        "false_doubled_rank_controls_rejected": True,
        "false_original_threshold_substitutions_rejected": True,
        "source_sha256": {p: hashlib.sha256((ROOT / p).read_bytes()).hexdigest() for p in paths},
        "generated_lean_sha256": hashlib.sha256(lean.encode()).hexdigest(),
    }
    return lean, json.dumps(data, indent=2) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    lean, data = construct()
    for path, expected in [(LEAN, lean), (DATA, data)]:
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
        elif path.read_bytes() != expected.encode():
            raise RuntimeError(f"Reification mismatch: {path.relative_to(ROOT)}")
    print("Reified 12×32 and 12×128 original populations; 12×64 baseline replay and false-rank controls pass.")


if __name__ == "__main__":
    main()
