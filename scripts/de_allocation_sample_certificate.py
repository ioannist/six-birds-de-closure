#!/usr/bin/env python3
"""Reify original IEEE allocation inputs and certify responses by rational margins.

Use the pinned sbt-de Python/NumPy. No optimization/root-finding solver is run.
Default replays bytes; --write creates new artifacts, preserving historical data.
"""
from fractions import Fraction as F
from pathlib import Path
import argparse,csv,hashlib,importlib.util,json,sys
import numpy as np

ROOT=Path(__file__).resolve().parents[1]
PRECISION=1_000_000
PRICES=[F(0),F(46112,100000),F(46113,100000),F(1,5),F(-1,5)]

def rat(q):return f'({q.numerator} / {q.denominator})'
def vec(name,qs):return f'def {name} : Fin {len(qs)} → ℚ :=\n  !['+', '.join(map(rat,qs))+']\n'
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()

def generate():
 assert np.__version__=='1.26.4',np.__version__
 source=ROOT/'scripts/de_dual_carrier.py'
 spec=importlib.util.spec_from_file_location('original_allocation',source)
 m=importlib.util.module_from_spec(spec);sys.modules[spec.name]=m;spec.loader.exec_module(m)
 cfg=m.DualConfig();ws,cs=m.make_patch_params(cfg)
 assert cfg.n_patches==32
 # Only original closed-form response arithmetic and budget construction.
 total=float(np.sum(m.unconstrained_x(ws,cs)))
 budgets=total*np.array([0.18,0.28,0.38,cfg.active_budget_fraction,0.62,0.82,0.98,1.02,1.15,cfg.slack_budget_factor])
 w=list(map(lambda x:F(float(x)),ws));c=list(map(lambda x:F(float(x)),cs));B=list(map(lambda x:F(float(x)),budgets))
 rows=list(csv.DictReader((ROOT/'results/DE_dual/patch_parameters.csv').open()))
 assert len(rows)==32
 for i,row in enumerate(rows):
  assert int(row['patch'])==i
  assert row['weight']==m.fmt(float(ws[i])) and row['curvature']==m.fmt(float(cs[i]))
 sweep=list(csv.DictReader((ROOT/'results/DE_dual/dual_sweep.csv').open()))
 assert len(sweep)==10
 assert [row['budget'] for row in sweep]==[m.fmt(float(x)) for x in budgets]
 vacuum=list(csv.DictReader((ROOT/'results/DE_dual/vacuum_shift.csv').open()))
 assert [row['budget'] for row in vacuum[:3]]==[m.fmt(float(budgets[3]))]*3
 offsets=[F(-0.2),F(0),F(0.2)]
 assert [row['offset'] for row in vacuum]==[m.fmt(float(x)) for x in offsets]*2
 local_rows=list(csv.DictReader((ROOT/'results/DE_dual/controls/local_budget_control.csv').open()))
 assert len(local_rows)==32
 assert all(int(row['patch'])==i and row['local_budget']==m.fmt(float(budgets[3])/32)
   for i,row in enumerate(local_rows))
 marginal=lambda wi,ci,x:wi/(1+x)-ci*x
 lower=[];upper=[]
 for p in PRICES:
  los=[];his=[]
  for wi,ci in zip(w,c):
   lo,hi=0,8*PRECISION
   assert p<marginal(wi,ci,F(lo,PRECISION)) and marginal(wi,ci,F(hi,PRECISION))<p
   while hi-lo>1:
    mid=(lo+hi)//2
    if p<=marginal(wi,ci,F(mid,PRECISION)):lo=mid
    else:hi=mid
   los.append(F(lo,PRECISION));his.append(F(hi,PRECISION))
  lower.append(los);upper.append(his)
 def validate(lows,highs):
  for q,p in enumerate(PRICES):
   for i,(wi,ci) in enumerate(zip(w,c)):
    assert 0<lows[q][i]<=highs[q][i]
    assert p<=marginal(wi,ci,lows[q][i]) and marginal(wi,ci,highs[q][i])<=p
 validate(lower,upper)
 bad=[xs.copy() for xs in lower];bad[1][0]=F(8)
 try:validate(bad,upper)
 except AssertionError:control=True
 else:raise AssertionError('false response certificate accepted')
 assert all(F(7,10)<wi<F(8,5) and F(1,5)<ci<F(41,100) for wi,ci in zip(w,c))
 assert all(0<b for b in B) and F(22)<B[3]<F(23)
 assert sum(lower[1])>B[3] and sum(upper[2])<B[3]
 assert all(b<sum(lower[0]) if j<7 else sum(upper[0])<b for j,b in enumerate(B))
 local=[marginal(wi,ci,B[3]/32) for wi,ci in zip(w,c)]
 assert all(0<p for p in local) and F(1,20)<local[1]-local[0]
 assert w[0]<w[1] and c[1]<c[0]
 candidates=[i for i in range(32) if F(1,2)<lower[0][i]-upper[3][i] and F(1,2)<lower[4][i]-upper[0][i]]
 assert candidates;cidx=candidates[0]
 decls=vec('weight',w)+vec('curvature',c)+vec('budgets',B)+vec('price',PRICES)+vec('offsets',offsets)
 for q in range(5):decls+=vec('lower'+str(q),lower[q])+vec('upper'+str(q),upper[q])
 decls+='def lower (q : Fin 5) : Fin 32 → ℚ := ![lower0, lower1, lower2, lower3, lower4] q\n'
 decls+='def upper (q : Fin 5) : Fin 32 → ℚ := ![upper0, upper1, upper2, upper3, upper4] q\n'
 decls+='def budget : ℚ := budgets 3\n'
 lean=f'''import Mathlib.Tactic

/-! Original IEEE coefficients/budgets; exact rational whole-response certificates.
Generated by de_allocation_sample_certificate.py. Original carrier/data unchanged. -/
namespace SbtCosmo.Derivation.AllocationSampleData
set_option maxRecDepth 100000
set_option maxHeartbeats 50000000

{decls}
theorem parameter_bounds : ∀ i : Fin 32,
    7/10 < weight i ∧ weight i < 8/5 ∧ 1/5 < curvature i ∧ curvature i < 41/100 := by
  decide +kernel

theorem budget_bounds : (∀ j : Fin 10, 0 < budgets j) ∧ 22 < budget ∧ budget < 23 := by
  decide +kernel

theorem cells : ∀ (q : Fin 5) (i : Fin 32),
    0 < lower q i ∧ lower q i ≤ upper q i ∧
      price q ≤ weight i/(1+lower q i)-curvature i*lower q i ∧
      weight i/(1+upper q i)-curvature i*upper q i ≤ price q := by
  decide +kernel

theorem price_mass_bounds : budget < ∑ i, lower 1 i ∧ (∑ i, upper 2 i) < budget := by
  decide +kernel

theorem sweep_mass_bounds : ∀ j : Fin 10,
    if j.val < 7 then budgets j < ∑ i, lower 0 i else (∑ i, upper 0 i) < budgets j := by
  decide +kernel

theorem source_shift_gaps :
    1/2 < lower 0 {cidx}-upper 3 {cidx} ∧ 1/2 < lower 4 {cidx}-upper 0 {cidx} := by
  decide +kernel

theorem local_price_control : (∀ i : Fin 32, 0 < weight i/(1+budget/32)-curvature i*(budget/32)) ∧
    1/20 < (weight 1/(1+budget/32)-curvature 1*(budget/32))-
      (weight 0/(1+budget/32)-curvature 0*(budget/32)) := by
  decide +kernel

theorem heterogeneity_order : weight 0 < weight 1 ∧ curvature 1 < curvature 0 := by
  decide +kernel

theorem original_offsets : (∀ j : Fin 3, -(1/4) ≤ offsets j ∧ offsets j ≤ 1/4) ∧
    offsets 0 < -(1/5) ∧ 1/5 < offsets 2 := by
  decide +kernel

end SbtCosmo.Derivation.AllocationSampleData
'''
 receipt={'arithmetic':'IEEE input reification; response certificates use Python Fraction only',
  'numpy_version':np.__version__,'coefficient_count':32,'budget_count':10,
  'coefficients_rng_used':False,'original_config_seed_unused_by_coefficient_generator':True,
  'optimizer_or_root_finding_solver_rerun':False,'csv_formatted_inputs_and_budgets_match':True,
  'original_source_sha256':sha(source),'historical_inputs_sha256':{
   str(p.relative_to(ROOT)):sha(p) for p in [ROOT/'results/DE_dual/patch_parameters.csv',ROOT/'results/DE_dual/dual_sweep.csv',ROOT/'results/DE_dual/vacuum_shift.csv',ROOT/'results/DE_dual/controls/local_budget_control.csv']},
  'weights':[{'hex':float(x).hex(),'rational':str(F(float(x)))} for x in ws],
  'curvatures':[{'hex':float(x).hex(),'rational':str(F(float(x)))} for x in cs],
  'budgets':[{'hex':float(x).hex(),'rational':str(F(float(x)))} for x in budgets],
  'offsets':[{'hex':float(x).hex(),'rational':str(x)} for x in offsets],
  'prices':list(map(str,PRICES)),'lower':[[str(x) for x in xs] for xs in lower],
  'upper':[[str(x) for x in xs] for xs in upper],
  'cells':160,'denominator':PRECISION,'false_cell_detected':control,
  'source_shift_witness_patch':cidx,'original_inputs_and_results_changed':False}
 return [(ROOT/'lean/SbtCosmo/Derivation/AllocationSampleData.lean',lean),
  (ROOT/'results/allocation_sample_2026-10-03/cells.json',json.dumps(receipt,indent=2)+'\n')]

def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--write',action='store_true');args=p.parse_args()
 for path,data in generate():
  if args.write:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(data)
  else:assert path.read_bytes()==data.encode(),str(path)
 print('Original32 coefficients,10 budgets and160 rational response cells verified; '+('artifacts written.' if args.write else 'byte replay matched.'))
if __name__=='__main__':main()
