#!/usr/bin/env python3
"""Reify the original twelve seed populations as exact rational Lean inputs.

The IEEE amplitudes are realized inputs, not a formalization of NumPy's RNG.
Declared model scalars use their exact decimal values. No ODE solver is run.
Use --write to regenerate; the default verifies byte-for-byte reproducibility.
"""
from __future__ import annotations

import argparse
from fractions import Fraction
import hashlib
import json
from pathlib import Path
import platform

import numpy as np

import de_window_carrier as window

ROOT = Path(__file__).resolve().parents[1]
LEAN = ROOT / "lean/SbtCosmo/Derivation/WindowSampleData.lean"
DATA = ROOT / "results/window_population_2026-10-03/population.json"


def rational(value: Fraction) -> str:
    return f"({value.numerator} / {value.denominator})"


def vector(values: list[str]) -> str:
    return "![" + ", ".join(values) + "]"


def construct() -> tuple[str, str]:
    if np.__version__ != "1.26.4":
        raise RuntimeError("The original frozen realization uses NumPy 1.26.4.")
    cfg = window.CarrierConfig()
    delta = Fraction(str(cfg.delta_c))
    required = next(
        k for k in range(len(window.SEEDS) + 1)
        if Fraction(k, len(window.SEEDS)) >= Fraction(str(cfg.seed_pass_fraction))
    )
    assert (cfg.n_patches, len(window.SEEDS), required) == (64, 12, 10)
    for passing in range(len(window.SEEDS) + 1):
        original_fraction = float(np.mean([True] * passing + [False] * (len(window.SEEDS) - passing)))
        assert (original_fraction >= cfg.seed_pass_fraction) == (passing >= required)
    rows = []
    for seed in window.SEEDS:
        rng = np.random.default_rng(seed)
        samples = cfg.heterogeneity_s * np.abs(rng.normal(size=cfg.n_patches))
        amplitudes = [Fraction.from_float(float(x)) for x in samples]
        tags = [bool(x) for x in rng.random(cfg.n_patches) < cfg.tag_probability]
        assert all(x >= 0 for x in amplitudes)
        indices = [max((i for i, t in enumerate(tags) if t == b), key=amplitudes.__getitem__)
                   for b in [False, True]]
        maxima = [amplitudes[i] for i in indices]
        assert all(x > 0 for x in maxima)
        threshold = max(delta / x for x in maxima)
        rows.append((seed, amplitudes, tags, indices, maxima, threshold))
    aggregate = sorted(row[5] for row in rows)[required - 1]
    previous = json.loads((ROOT / "results/original_claim_checks_2026-10-02/receipt.json").read_text())
    historical = previous["window_threshold"]
    assert [str(row[5]) for row in rows] == historical["seed_thresholds_exact"]
    assert required == historical["required_seeds"]
    assert str(aggregate) == historical["aggregate_threshold_exact"]

    definitions = {
        "amplitudeRat : Fin 12 → Fin 64 → ℚ": vector([
            vector([rational(x) for x in row[1]]) for row in rows]),
        "tag : Fin 12 → Fin 64 → Bool": vector([
            vector([str(b).lower() for b in row[2]]) for row in rows]),
        "falseIndex : Fin 12 → Fin 64": vector([str(row[3][0]) for row in rows]),
        "trueIndex : Fin 12 → Fin 64": vector([str(row[3][1]) for row in rows]),
        "maximumFalseRat : Fin 12 → ℚ": vector([rational(row[4][0]) for row in rows]),
        "maximumTrueRat : Fin 12 → ℚ": vector([rational(row[4][1]) for row in rows]),
        "thresholdRat : Fin 12 → ℚ": vector([rational(row[5]) for row in rows]),
        "deltaRat : ℚ": rational(delta),
        "aggregateRat : ℚ": rational(aggregate),
    }
    lean = """import Mathlib.Tactic

/-! Exact realized inputs from NumPy 1.26.4 and the original carrier's seeds 1100..1111.
Generated by scripts/de_window_reification.py; all proofs below run in Lean's kernel.
The random-number algorithm and its probability law are not formalized here. -/
namespace SbtCosmo.Derivation.WindowSampleData

set_option maxRecDepth 100000
set_option maxHeartbeats 20000000

"""
    lean += "\n\n".join("def " + name + " :=\n  " + value for name, value in definitions.items())
    lean += """

theorem rational_maxima_certificate : ∀ j : Fin 12,
    0 < maximumFalseRat j ∧ 0 < maximumTrueRat j ∧
    tag j (falseIndex j) = false ∧ amplitudeRat j (falseIndex j) = maximumFalseRat j ∧
    tag j (trueIndex j) = true ∧ amplitudeRat j (trueIndex j) = maximumTrueRat j ∧
    ∀ i : Fin 64, 0 ≤ amplitudeRat j i ∧
      (tag j i = false → amplitudeRat j i ≤ maximumFalseRat j) ∧
      (tag j i = true → amplitudeRat j i ≤ maximumTrueRat j) := by
  decide +kernel

theorem rational_threshold_certificate : ∀ j : Fin 12,
    thresholdRat j = max (deltaRat / maximumFalseRat j) (deltaRat / maximumTrueRat j) := by
  decide +kernel

theorem rational_rank_certificate :
    (Finset.univ.filter (fun j : Fin 12 => thresholdRat j < aggregateRat)).card = 9 ∧
    (Finset.univ.filter (fun j : Fin 12 => thresholdRat j ≤ aggregateRat)).card = 10 := by
  decide +kernel

theorem rational_window_bounds : (3 : ℚ) / 2 < aggregateRat ∧ aggregateRat < 20000 := by
  decide +kernel

end SbtCosmo.Derivation.WindowSampleData
"""
    inputs = ["scripts/de_window_reification.py", "scripts/de_window_carrier.py",
              "scripts/de_original_claim_checks.py",
              "results/original_claim_checks_2026-10-02/receipt.json"]
    data = {
        "scope": "Exact IEEE amplitude and Bool-tag reification of the original realized twelve populations; no ODE solve or RNG proof",
        "software": {"python": platform.python_version(), "numpy": np.__version__},
        "model_scalars_decimal": {"a_init": str(cfg.a_init), "a_max": str(cfg.a_max),
                                  "delta_c": str(cfg.delta_c), "seed_pass_fraction": str(cfg.seed_pass_fraction)},
        "required_seeds": required,
        "original_float_fraction_cases_checked": len(window.SEEDS) + 1,
        "populations": [{"seed": row[0], "amplitudes_exact": [str(x) for x in row[1]],
                         "tags": row[2], "tag_maximum_indices": row[3],
                         "tag_maxima_exact": [str(x) for x in row[4]],
                         "threshold_exact": str(row[5])} for row in rows],
        "aggregate_threshold_exact": str(aggregate),
        "rank_counts": {"strictly_below": sum(row[5] < aggregate for row in rows),
                        "at_or_below": sum(row[5] <= aggregate for row in rows)},
        "source_sha256": {p: hashlib.sha256((ROOT / p).read_bytes()).hexdigest() for p in inputs},
        "generated_lean_sha256": hashlib.sha256(lean.encode()).hexdigest(),
    }
    return lean, json.dumps(data, indent=2) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    lean, data = construct()
    for path, expected in [(LEAN, lean), (DATA, data)]:
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
        elif path.read_bytes() != expected.encode():
            raise RuntimeError(f"Reification mismatch: {path.relative_to(ROOT)}")
    print("Reified 12 × 64 exact amplitudes/tags; maxima and rank match the historical receipt.")


if __name__ == "__main__":
    main()
