#!/usr/bin/env python3
"""Exact rational cell certificates for the native growth quadrature.

No floating arithmetic, RNG, or ODE solver is used. The generated Lean file
checks every certificate in the kernel. Default mode replays expected bytes;
--write explicitly regenerates the two certificate artifacts.
"""

from __future__ import annotations

import argparse
from fractions import Fraction
import json
from math import isqrt
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LEAN = ROOT / "lean/SbtCosmo/Derivation/GrowthQuadratureData.lean"
RECEIPT = ROOT / "results/growth_quadrature_2026-10-03/cells.json"
PRECISION = 1_000_000


def rational(value: Fraction) -> str:
    return f"({value.numerator} / {value.denominator})"


def generate() -> tuple[str, str]:
    f = Fraction
    grid = (
        [f(1, 1000)]
        + [f(j, 128) for j in range(1, 129)]
        + [f(j, 64) for j in range(65, 129)]
        + [f(j, 16) for j in range(33, 65)]
        + [f(j, 4) for j in range(17, 33)]
        + [f(j, 2) for j in range(17, 41)]
    )
    assert len(grid) == 265 and grid[0] == f(1, 1000) and grid[-1] == 20
    lower, upper = [], []
    for a, b in zip(grid, grid[1:]):
        assert 0 < a < b
        qlo = a**3 / (1 + 3 * b**3) ** 3
        qhi = b**3 / (1 + 4 * a**3) ** 3
        lower.append(f(isqrt(qlo.numerator * PRECISION**2 // qlo.denominator), PRECISION))
        upper.append(f(isqrt(qhi.numerator * PRECISION**2 // qhi.denominator) + 1, PRECISION))

    def validate(lows: list[Fraction], highs: list[Fraction]) -> None:
        for a, b, lo, hi in zip(grid, grid[1:], lows, highs, strict=False):
            assert 0 <= lo and 0 <= hi
            assert lo**2 * (1 + 3 * b**3) ** 3 <= a**3
            assert b**3 <= (1 + 3 * a**3) ** 3
            assert b**3 <= hi**2 * (1 + 4 * a**3) ** 3

    validate(lower, upper)
    bad = lower.copy()
    bad[0] = f(1)
    try:
        validate(bad, upper)
    except AssertionError:
        mutation_detected = True
    else:
        raise AssertionError("False lower certificate escaped validation")
    low_sum = sum(((b - a) * lo for a, b, lo in zip(grid, grid[1:], lower)), f(0))
    high_sum = sum(((b - a) * hi for a, b, hi in zip(grid, grid[1:], upper)), f(0))
    assert f(2227, 10000) <= low_sum and high_sum <= f(187, 1000)
    vector = lambda values: "![" + ", ".join(map(rational, values)) + "]"
    lean = f'''import Mathlib.Tactic

/-! Exact native-scale cell bounds, generated by scripts/de_growth_quadrature_certificate.py.
All numerical inequalities are checked with Lean's kernel. -/
namespace SbtCosmo.Derivation.GrowthQuadratureData
set_option maxRecDepth 100000
set_option maxHeartbeats 20000000

def gridValues : Fin 265 → ℚ :=
  {vector(grid)}
def lowerValues : Fin 264 → ℚ :=
  {vector(lower)}
def upperValues : Fin 264 → ℚ :=
  {vector(upper)}

def grid (i : ℕ) : ℚ := if h : i < 265 then gridValues ⟨i, h⟩ else 20
def lower (i : ℕ) : ℚ := if h : i < 264 then lowerValues ⟨i, h⟩ else 0
def upper (i : ℕ) : ℚ := if h : i < 264 then upperValues ⟨i, h⟩ else 1

theorem grid_endpoints : grid 0 = (1 : ℚ) / 1000 ∧ grid 264 = 20 := by
  decide +kernel

theorem lower_cells : ∀ i : Fin 264,
    0 < grid i ∧ grid i ≤ grid (i + 1) ∧ 0 ≤ lower i ∧
      (lower i)^2 * (1 + 3 * (grid (i + 1))^3)^3 ≤ (grid i)^3 ∧
      (grid (i + 1))^3 ≤ (1 + 3 * (grid i)^3)^3 := by
  decide +kernel

theorem upper_cells : ∀ i : Fin 264,
    0 < grid i ∧ grid i ≤ grid (i + 1) ∧ 0 ≤ upper i ∧
      (grid (i + 1))^3 ≤ (upper i)^2 * (1 + 4 * (grid i)^3)^3 := by
  decide +kernel

theorem lower_sum : (2227 : ℚ) / 10000 ≤
    ∑ i ∈ Finset.range 264, (grid (i + 1) - grid i) * lower i := by
  decide +kernel

theorem upper_sum : (∑ i ∈ Finset.range 264, (grid (i + 1) - grid i) * upper i) ≤ (187 : ℚ) / 1000 := by
  decide +kernel

end SbtCosmo.Derivation.GrowthQuadratureData
'''
    receipt = {
        "arithmetic": "Python Fraction and integer isqrt; no floating arithmetic",
        "cells": 264,
        "sqrt_enclosure_denominator": PRECISION,
        "lower_lambda": "3",
        "upper_lambda": "4",
        "domain": ["1/1000", "20"],
        "lower_integral_sum": str(low_sum),
        "upper_integral_sum": str(high_sum),
        "lower_integral_certificate": "2227/10000",
        "upper_integral_certificate": "187/1000",
        "false_lower_certificate_detected": mutation_detected,
        "grid": list(map(str, grid)),
        "lower": list(map(str, lower)),
        "upper": list(map(str, upper)),
    }
    return lean, json.dumps(receipt, indent=2) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    lean, receipt = generate()
    for path, content in ((LEAN, lean), (RECEIPT, receipt)):
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        else:
            assert path.read_bytes() == content.encode(), f"Certificate drift: {path}"
    print("Exact 264-cell certificates and false-certificate control passed; "
          + ("artifacts written." if args.write else "artifact byte replay matched."))


if __name__ == "__main__":
    main()
