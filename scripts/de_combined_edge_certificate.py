#!/usr/bin/env python3
"""Exact rational quadrature profiles for combined population/knob robustness.

Fraction/isqrt enclosures; no floating arithmetic, RNG or ODE solver.
Default replays bytes. --write creates new artifacts without altering prior ones.
"""
from fractions import Fraction as F
from math import isqrt
from pathlib import Path
import argparse,json
ROOT=Path(__file__).resolve().parents[1]
PRECISION=1_000_000
PROFILES=[('CombinedEdgeLowerData',F(5,2),F(3,500),F(4),'lower',F(245,1000)),
          ('CombinedEdgePrefixData',F(7,2),F(3,500),F(8,3),'lower',F(1908,10000)),
          ('CombinedEdgeUpperData',F(7,2),F(1,5000),F(120),'upper',F(2036,10000))]

def rat(q):return f'({q.numerator} / {q.denominator})'
def chunked(name,vs,default):
 chunks=[vs[i:i+128] for i in range(0,len(vs),128)]
 out=''.join(f'def {name}Block{k} : Fin {len(block)} → ℚ :=\n  !['+', '.join(map(rat,block))+']\n' for k,block in enumerate(chunks))
 out+=f'def {name} (i : ℕ) : ℚ :=\n  '
 for k,block in enumerate(chunks):
  ix='i' if k==0 else f'i - {k*128}'
  out+=f'if h : i < {k*128+len(block)} then {name}Block{k} ⟨{ix}, by omega⟩ else\n  '
 return out+rat(default)+'\n'

def generate():
 outputs=[];receipts=[]
 for mod,lam,start,end,kind,cap in PROFILES:
  grid=sorted({start,end}|{F(j,320) for j in range(1,321) if start<F(j,320)<end}
      |{F(j,160) for j in range(161,321) if start<F(j,160)<end}
      |{F(j,64) for j in range(129,257) if start<F(j,64)<end}
      |{F(j,12) for j in range(49,97) if start<F(j,12)<end}
      |{F(j,4) for j in range(33,81) if start<F(j,4)<end}
      |{F(j) for j in range(21,101) if start<F(j)<end})
  q=lambda a:a**3/(1+lam*a**3)**3
  sqrtfloor=lambda x:F(isqrt(x.numerator*PRECISION**2//x.denominator),PRECISION)
  bounds=[]
  for a,b in zip(grid,grid[1:]):
   if kind=='lower':bounds.append(sqrtfloor(min(q(a),q(b))))
   else:
    val=q(b) if 2*lam*b**3<=1 else q(a) if 1<=2*lam*a**3 else F(4)/(27*lam)
    bounds.append(sqrtfloor(val)+F(1,PRECISION))
  def valid(bds):
   for a,b,v in zip(grid,grid[1:],bds):
    assert 0<a<=b and 0<=v
    if kind=='lower':
     assert v*v*(1+lam*a**3)**3<=a**3
     assert v*v*(1+lam*b**3)**3<=b**3
    else:
     assert ((2*lam*b**3<=1 and b**3<=v*v*(1+lam*b**3)**3)
         or (1<=2*lam*a**3 and a**3<=v*v*(1+lam*a**3)**3) or 4<=27*lam*v*v)
  valid(bounds)
  bad=bounds.copy();bad[0]=F(1) if kind=='lower' else F(0)
  try:valid(bad)
  except AssertionError:control=True
  else:raise AssertionError('False cell certificate accepted: '+mod)
  total=sum(((b-a)*v for a,b,v in zip(grid,grid[1:],bounds)),F(0))
  assert cap<=total if kind=='lower' else total<=cap
  n=len(bounds);decls=chunked('grid',grid,end)+chunked('bound',bounds,F(0) if kind=='lower' else F(1))
  l=rat(lam)
  cell=(f'(bound i)^2 * (1 + {l} * (grid i)^3)^3 ≤ (grid i)^3 ∧\n'
        f'      (bound i)^2 * (1 + {l} * (grid (i+1))^3)^3 ≤ (grid (i+1))^3' if kind=='lower' else
        f'((2 * {l} * (grid (i+1))^3 ≤ 1 ∧\n'
        f'        (grid (i+1))^3 ≤ (bound i)^2 * (1 + {l} * (grid (i+1))^3)^3) ∨\n'
        f'      (1 ≤ 2 * {l} * (grid i)^3 ∧\n'
        f'        (grid i)^3 ≤ (bound i)^2 * (1 + {l} * (grid i)^3)^3) ∨\n'
        f'      4 ≤ 27 * {l} * (bound i)^2)')
  sumexpr=f'∑ i ∈ Finset.range {n}, (grid (i+1)-grid i)*bound i'
  comparison=f'{rat(cap)} ≤\n    {sumexpr}' if kind=='lower' else f'({sumexpr}) ≤ {rat(cap)}'
  lean=f'''import Mathlib.Tactic

/-! Exact fixed-profile whole-cell certificate; generated by de_combined_edge_certificate.py.
All inequalities checked by Lean's kernel. -/
namespace SbtCosmo.Derivation.{mod}
set_option maxRecDepth 100000
set_option maxHeartbeats 50000000

{decls}
theorem grid_endpoints : grid 0 = {rat(start)} ∧ grid {n} = {rat(end)} := by
  decide +kernel

theorem cells : ∀ i : Fin {n},
    0 < grid i ∧ grid i ≤ grid (i+1) ∧ 0 ≤ bound i ∧
      {cell} := by
  decide +kernel

theorem integral_sum : {comparison} := by
  decide +kernel

end SbtCosmo.Derivation.{mod}
'''
  outputs.append((ROOT/f'lean/SbtCosmo/Derivation/{mod}.lean',lean))
  receipts.append({'module':mod,'lambda':str(lam),'domain':[str(start),str(end)],'direction':kind,
    'cells':n,'integral_sum':str(total),'integral_bound':str(cap),'false_cell_detected':control,
    'grid':list(map(str,grid)),'bounds':list(map(str,bounds))})
 receipt={'arithmetic':'Python Fraction and integer isqrt; no floating arithmetic','sqrt_denominator':PRECISION,
          'profiles':receipts,'original_inputs_and_previous_certificates_changed':False}
 outputs.append((ROOT/'results/combined_robustness_2026-10-03/cells.json',json.dumps(receipt,indent=2)+'\n'))
 return outputs

def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--write',action='store_true');args=p.parse_args()
 outputs=generate()
 for path,data in outputs:
  if args.write:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(data)
  else:assert path.read_bytes()==data.encode(),str(path)
 print('Three exact profiles and false-cell controls passed; '+('artifacts written.' if args.write else 'byte replay matched.'))
if __name__=='__main__':main()
