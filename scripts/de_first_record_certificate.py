#!/usr/bin/env python3
"""Exact prefix quadrature certificates for original first-record ratio bounds.

Fraction/isqrt only. Default mode replays bytes; --write generates artifacts.
The rational population bound is checked against the existing reified input
inside Lean, rather than by a second population realization.
"""
from __future__ import annotations
import argparse
from fractions import Fraction
import json
from math import isqrt
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LEAN = ROOT / 'lean/SbtCosmo/Derivation/WindowFirstRecordData.lean'
RECEIPT = ROOT / 'results/first_record_2026-10-03/cells.json'
PRECISION = 1_000_000


def generate() -> tuple[str, str]:
    f = Fraction
    grid = [f(1, 1000)] + [f(j, 256) for j in range(1, 257)] + [f(j, 128) for j in range(129, 257)]
    lower = []
    for a, b in zip(grid, grid[1:]):
        q = a**3 / (1 + 3 * b**3)**3
        lower.append(f(isqrt(q.numerator * PRECISION**2 // q.denominator), PRECISION))
    def validate(bounds: list[Fraction]) -> None:
        for a, b, lo in zip(grid, grid[1:], bounds):
            assert 0 < a <= b and 0 <= lo
            assert lo**2 * (1 + 3 * b**3)**3 <= a**3
            assert b**3 <= (1 + 3 * a**3)**3
    validate(lower)
    bad = lower.copy()
    bad[0] = f(1)
    try:
        validate(bad)
    except AssertionError:
        mutation_detected = True
    else:
        raise AssertionError('False lower certificate escaped validation')
    total = sum(((b-a)*lo for a, b, lo in zip(grid, grid[1:], lower)), f(0))
    assert len(lower) == 384 and f(204, 1000) <= total
    def vector(values: list[Fraction]) -> str:
        return '![' + ', '.join(f'({v.numerator} / {v.denominator})' for v in values) + ']'
    lean = f'''import SbtCosmo.Derivation.WindowSampleData

/-! Kernel-checked original first-collapse thresholds and prefix quadrature.
Generated by scripts/de_first_record_certificate.py. -/
namespace SbtCosmo.Derivation.WindowFirstRecordData
set_option maxRecDepth 100000
set_option maxHeartbeats 30000000

open WindowSampleData

def firstThresholdRat (j : Fin 12) : ℚ :=
  deltaRat / max (maximumFalseRat j) (maximumTrueRat j)

theorem first_threshold_bounds : ∀ j : Fin 12,
    (500 : ℚ) < firstThresholdRat j ∧ firstThresholdRat j < 897 := by
  decide +kernel

def gridValues : Fin 385 → ℚ :=
  {vector(grid)}
def lowerValues : Fin 384 → ℚ :=
  {vector(lower)}
def grid (i : ℕ) : ℚ := if h : i < 385 then gridValues ⟨i, h⟩ else 2
def lower (i : ℕ) : ℚ := if h : i < 384 then lowerValues ⟨i, h⟩ else 0

theorem grid_endpoints : grid 0 = (1 : ℚ) / 1000 ∧ grid 384 = 2 := by
  decide +kernel

theorem lower_cells : ∀ i : Fin 384,
    0 < grid i ∧ grid i ≤ grid (i + 1) ∧ 0 ≤ lower i ∧
      (lower i)^2 * (1 + 3 * (grid (i + 1))^3)^3 ≤ (grid i)^3 ∧
      (grid (i + 1))^3 ≤ (1 + 3 * (grid i)^3)^3 := by
  decide +kernel

theorem lower_sum : (204 : ℚ) / 1000 ≤
    ∑ i ∈ Finset.range 384, (grid (i + 1) - grid i) * lower i := by
  decide +kernel

end SbtCosmo.Derivation.WindowFirstRecordData
'''
    receipt = {
        'arithmetic': 'Python Fraction and integer isqrt; no floating arithmetic',
        'cells': 384, 'sqrt_enclosure_denominator': PRECISION,
        'lambda': '3', 'domain': ['1/1000', '2'],
        'lower_integral_sum': str(total), 'lower_integral_certificate': '204/1000',
        'false_lower_certificate_detected': mutation_detected,
        'population_source': 'unchanged WindowSampleData.lean',
        'grid': list(map(str, grid)), 'lower': list(map(str, lower))}
    return lean, json.dumps(receipt, indent=2) + '\n'


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    lean, receipt = generate()
    for path, content in ((LEAN, lean), (RECEIPT, receipt)):
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        else:
            assert path.read_bytes() == content.encode(), f'Certificate drift: {path}'
    print('Exact 384-cell prefix certificate and false-certificate control passed; '
          + ('artifacts written.' if args.write else 'artifact byte replay matched.'))


if __name__ == '__main__':
    main()
